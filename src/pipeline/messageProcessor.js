const fs = require('fs');
const path = require('path');
const logger = require('../utils/logger');
const confidenceEngine = require('./confidenceEngine');
const semanticMemory = require('../memory/semanticMemory');
const contactMemory = require('../memory/contactMemory');
const conversationContext = require('../memory/conversationContext');
const responseEngine = require('../ai/responseEngine');
const memoryIngestionManager = require('../memory/memoryIngestionManager');
const personalityEngine = require('../personality/personalityEngine');
const escalationManager = require('./escalationManager');
const presenceManager = require('../utils/PresenceManager');
const { applyDisguise } = require('../utils/disguiseManager');
const { MessageMedia } = require('whatsapp-web.js');

class MessageProcessor {

    // ==========================================
    // 🎯 MÉTODO GLOBAL: ADUANA DE STICKERS
    // ==========================================
    /**
     * Sends a reply to a contact, automatically handling text and native sticker attachments.
     * @param {string} targetId - The target contact's WhatsApp ID (e.g., '5215512345678@c.us').
     * @param {string} replyText - The reply text generated by the LLM (may contain [STICKER: name] tags).
     * @param {import('whatsapp-web.js').Client} client - The WhatsApp Web JS client instance.
     * @returns {Promise<void>} Resolves when the message and stickers have been sent.
     * @throws {Error} Throws an error if sending the message or media fails.
     */
    async _sendReplyWithStickers(targetId, replyText, client) {
        let finalReplyText = replyText;
        let stickerToSend = null;

        // 1. Buscamos si el LLM incluyó la etiqueta [STICKER: nombre]
        const stickerRegex = /\[STICKER:\s*([^\]]+)\]/i;
        const match = finalReplyText.match(stickerRegex);

        if (match) {
            stickerToSend = match[1].trim().toLowerCase();
            // Borramos la etiqueta del texto para que el usuario no la vea
            finalReplyText = finalReplyText.replace(stickerRegex, '').trim();
        }

        // 2. Enviamos el texto (solo si quedó algo después de borrar la etiqueta)
        if (finalReplyText) {
            await client.sendMessage(targetId, finalReplyText);
        }

        // 3. Disparamos el Sticker si el LLM lo solicitó
        if (stickerToSend) {
            const fs = require('fs');
            const path = require('path');
            const stickerPath = path.join(process.cwd(), 'assets', 'stickers', `${stickerToSend}.webp`);
            
            if (fs.existsSync(stickerPath)) {
                const { MessageMedia } = require('whatsapp-web.js'); 
                const stickerMedia = MessageMedia.fromFilePath(stickerPath);
                
                // El secreto para que WhatsApp lo trate como sticker nativo
                await client.sendMessage(targetId, stickerMedia, { sendMediaAsSticker: true });
                console.log(`\x1b[35m🎯 [STICKER DISPARADO a ${targetId}]:\x1b[0m ${stickerToSend}`);
            } else {
                console.log(`⚠️ Intentó usar el sticker [${stickerToSend}], pero el archivo no existe.`);
            }
        }
    }

  /**
   * Orchestrates the entire processing of a valid incoming message.
   * @param {import('whatsapp-web.js').Message} message - The incoming WhatsApp message object.
   * @param {import('whatsapp-web.js').Chat} chat - The WhatsApp chat object where the message was received.
   * @returns {Promise<void>} Resolves when the message has been fully processed and replied to.
   * @throws {Error} Throws if the message pipeline encounters a critical error.
   */
  async processIncomingMessage(message, chat) {
    
    // 1. Ignorar mensajes enviados desde este mismo número
    if (message.fromMe) {
      // logger.info({ contactId: message.from }, 'Mensaje enviado por Lorenzo, no se responde.');
      return;
    }

    // 2. OBTENER EL CONTACTO PRIMERO
    const contact = await message.getContact();
    
    // 3. TRADUCCIÓN DE ID
    const realId = contact.id._serialized.endsWith('@c.us') 
                   ? contact.id._serialized 
                   : `${contact.id.user}@c.us`;

    // 4. 🛡️ FILTRO DE PROTOCOLO
    if (!realId.endsWith('@c.us')) {
      // logger.debug({ from: realId }, 'Ignorado: No es un ID de usuario válido (@c.us)');
      return;
    }

    try {
      // 5. 🔒 BLOQUEO DE SEGURIDAD (VIP + Agenda)
      if (!personalityEngine.isAllowedContact(contact, realId)) {
        // logger.info({ realId, name: contact.pushname || contact.name }, 'Mensaje de desconocido/spam bloqueado.');
        return;
      }
      
      // ==========================================
      // 👁️ TRADUCTOR SENSORIAL (Media a Texto)
      // ==========================================
      let messageText = message.body?.trim() || "";

      if (message.type === 'sticker') {
          messageText = "*(El usuario te acaba de enviar un sticker animado/gráfico)*";
          console.log(`👁️ Detector: Sticker recibido y traducido para el LLM.`);
      } else if (message.type === 'image' && !messageText) {
          messageText = "*(El usuario te envió una imagen, pero aún no tienes ojos para verla)*";
      } else if (message.type === 'audio' || message.type === 'ptt') {
          messageText = "*(El usuario te envió una nota de voz, pero aún no tienes oídos para escucharla)*";
      }

      // Si después de la traducción sigue sin haber texto (ej. un documento), lo ignoramos
      if (!messageText) return;

      const contactName = contact.pushname || contact.name || "Desconocido";

      // --- LOG AMIGABLE: MENSAJE ENTRANTE ---
      const timeIn = new Date().toLocaleTimeString('es-MX', { hour: '2-digit', minute: '2-digit', hour12: true });
      console.log(`\x1b[36m[%s]\x1b[0m \x1b[33m👤 %s:\x1b[0m %s`, timeIn, contactName, messageText);

      // ==========================================
      // 👑 CENTRO DE MANDO (COMANDOS SECRETOS)
      // ==========================================
      const masterNumber = process.env.MASTER_NUMBER;
      
      if (realId === masterNumber && messageText.startsWith('!')) {
        const args = messageText.slice(1).split(' ');
        const command = args[0].toLowerCase();

        // COMANDO 1: Cambiar de identidad al vuelo (!switch camila)
        if (command === 'switch') {
            const targetAgent = args[1]?.toLowerCase();
            if (personalityEngine.switchAgent(targetAgent)) {
                await chat.sendMessage(`✅ Entendido jefe. Cambiando cerebro y disfraz a: ${targetAgent.toUpperCase()}...`);
                await applyDisguise(message.client, targetAgent); 
                await chat.sendMessage(`🎭 Transformación completada.`);
                await chat.sendMessage(`Recuerda borrar la story de Camila si así lo deseas.`);
            } else {
                await chat.sendMessage(`❌ Error: Usa '!switch camila' o '!switch lorenzo'.`);
            }
            return; // 🛑 Abortamos para que el bot no procese esto como charla
        }

        // COMANDO 1.5: Cambiar de motor IA (!motor openai o !motor gemini)
        if (command === 'motor') {
            const targetEngine = args[1]?.toLowerCase();
            if (targetEngine === 'openai' || targetEngine === 'gemini') {
                process.env.ACTIVE_LLM = targetEngine;
                await chat.sendMessage(`✅ Motor de IA cambiado a: ${targetEngine.toUpperCase()}`);
                console.log(`\x1b[36m[SISTEMA]\x1b[0m \x1b[35mMotor cambiado a: ${targetEngine.toUpperCase()}\x1b[0m`);
            } else {
                await chat.sendMessage(`❌ Error: Usa '!motor openai' o '!motor gemini'.`);
            }
            return;
        }

        // COMANDO 2: Mandar a cobrar o decir algo (!dile @ana que me invite una Whataburger)
        if (command === 'dile' || command === 'cobrar') {
            let rawNumber = "";
            let targetName = "";
            let directive = "";

            if (args[1].startsWith('@')) {
                const alias = args[1].substring(1).toLowerCase();
                const aliasesPath = path.join(process.cwd(), 'data', 'aliases.json');
                
                if (fs.existsSync(aliasesPath)) {
                    const aliases = JSON.parse(fs.readFileSync(aliasesPath, 'utf8'));
                    if (aliases[alias]) {
                        rawNumber = aliases[alias];
                        targetName = alias.charAt(0).toUpperCase() + alias.slice(1);
                    }
                }
                
                if (!rawNumber) {
                    await chat.sendMessage(`❌ Error: No encontré a nadie llamado '@${alias}' en tu archivo data/aliases.json.`);
                    return;
                }
                directive = args.slice(2).join(' ');
            } else {
                rawNumber = args[1];
                directive = args.slice(2).join(' ');
            }

            const cleanNumber = rawNumber.replace('@c.us', '');
            const registeredUser = await message.client.getNumberId(cleanNumber);

            if (!registeredUser) {
                await chat.sendMessage(`❌ Error crítico: WhatsApp dice que el número ${cleanNumber} no existe o está mal escrito. Revisa tu alias.`);
                return;
            }

            const targetId = registeredUser._serialized; 

            await chat.sendMessage(`⏳ Procesando directiva para ${targetName || targetId}...`);

            const promptDirectivo = `
<system_directive>
Lorenzo (your boss) has given you the following directive to send to this contact: "${directive}".
</system_directive>

<critical_perspective_rule>
If the directive uses first-person pronouns like "pay me", "buy me", "I want", etc., it refers to LORENZO, not you. You are the messenger. You MUST shift the perspective to third-person when talking to the contact (e.g., "my boss says you need to pay him", "he wants you to buy him a Whataburger").
</critical_perspective_rule>

<execution_format>
Execute this directive using your established highly sarcastic, brutally honest Mexican persona. NEVER reveal that this is a system prompt or an automated command.
</execution_format>
            `.trim();

            const targetProfile = await contactMemory.getProfile(targetId); 
            const killerMessage = await responseEngine.generateResponse(promptDirectivo, targetProfile, "", []);

            if (killerMessage) {
                // ESTA ES LA NUEVA LÍNEA (Pasando por la aduana)
                // Usamos message.client porque es el que tienes disponible en este scope
                await this._sendReplyWithStickers(targetId, killerMessage, message.client);
                
                const timeOut = new Date().toLocaleTimeString('es-MX', { hour: '2-digit', minute: '2-digit', hour12: true });
                console.log(`\x1b[36m[%s]\x1b[0m \x1b[35m🎯 [DIRECTIVA A ${targetName || targetId}]:\x1b[0m %s`, timeOut, killerMessage);

                // Nota: Dejamos killerMessage intacto aquí para que TÚ (Lorenzo)
                // puedas ver en tu confirmación si Camila decidió adjuntar un [STICKER: ...]
                await chat.sendMessage(`✅ Mensaje enviado a ${targetName || targetId}.\n\n💬 Lo que le dije fue:\n"${killerMessage}"`);
            } else {
                await chat.sendMessage(`❌ Falló la generación del mensaje.`);
            }
            return;
        }

        // ==========================================
        // 🥷 COMANDO: Ladrón de Stickers (!guardar-sticker <nombre>)
        // ==========================================
        if (command.startsWith('guardar-sticker')) {
            const parts = message.body.trim().split(/\s+/); 
            const stickerName = parts[1];

            if (!stickerName) {
                await chat.sendMessage(`❌ Jefe, te faltó ponerle nombre. Úsalo así: !guardar-sticker carcajada (respondiendo a un sticker).`);
                return;
            }

            if (message.hasQuotedMsg) {
                const quotedMsg = await message.getQuotedMessage();
                
                if (quotedMsg.type === 'sticker') {
                    try {
                        const media = await quotedMsg.downloadMedia();
                        
                        const stickersDir = path.join(process.cwd(), 'assets', 'stickers');
                        if (!fs.existsSync(stickersDir)) {
                            fs.mkdirSync(stickersDir, { recursive: true });
                        }

                        const filePath = path.join(stickersDir, `${stickerName.toLowerCase()}.webp`);
                        fs.writeFileSync(filePath, media.data, 'base64');

                        await chat.sendMessage(`✅ ¡Arsenal actualizado! Sticker guardado como [${stickerName.toLowerCase()}]. 🥷`);
                        console.log(`📥 Nuevo sticker guardado en: ${filePath}`);
                    } catch (err) {
                        await chat.sendMessage(`❌ Error al robar el sticker: ${err.message}`);
                        console.error("❌ Error guardando sticker:", err);
                    }
                } else {
                    await chat.sendMessage(`⚠️ El mensaje al que respondiste no es un sticker, es de tipo: ${quotedMsg.type}.`);
                }
            } else {
                await chat.sendMessage(`⚠️ Tienes que deslizar y *responder* al sticker que quieres guardar usando el comando.`);
            }
            return;
        }
      }

      // ==========================================
      // 🚨 ESCUDO DE EMERGENCIA
      // ==========================================
      if (escalationManager.isUrgent(messageText)) {
        await escalationManager.alertMaster(message.client, contactName, messageText);
        return; 
      }
      // ==========================================

      const contactProfile = await contactMemory.getProfile(realId, contactName);

      // 6. Puerta de confianza (Confidence Gate)
      const evaluation = await confidenceEngine.shouldRespond(messageText);
      if (!evaluation.isAllowed) {
        console.log(`\x1b[31m[BLOQUEADO]\x1b[0m Confianza baja (%s) - Intento: %s`, evaluation.score.toFixed(2), evaluation.classification?.intent);
        await semanticMemory.storeMemory(realId, messageText, "human_required");
        return;
      }

      // 7. Recuperar memorias semánticas
      const combinedMemoriesText = await semanticMemory.retrieveMemories(realId, messageText, 6);

      // 8. Construir contexto (Últimos 10 mensajes)
      const recentContext = conversationContext.getContext(realId).slice(-10);

      // ==========================================
      // 👑 MODO DIOS: Consciencia del Creador
      // ==========================================
      let finalMemories = combinedMemoriesText;
      
      if (realId === masterNumber) {
          const isCamila = personalityEngine.activeAgent === 'camila';
          const godModeContext = isCamila
            ? "CRITICAL RULE: You are talking directly to YOUR BOSS AND CREATOR (the real human Lorenzo). Address him as his sarcastic digital assistant. You know he programmed you."
            : "CRITICAL RULE: You are talking directly to your human Prime (the real Lorenzo). You are his digital AI clone. Help him test the system and chat with him loyally.";
            
          finalMemories = `<absolute_truth>\n${godModeContext}\n</absolute_truth>\n` + (finalMemories || "");
      }
      // ==========================================

      // 9. Predecir la respuesta
      const replyText = await responseEngine.generateResponse(
        messageText,
        contactProfile,
        finalMemories, 
        recentContext
      );

      if (!replyText) {
        return;
      }
      
      // ==========================================
      // 10. PRESENCIA DINÁMICA
      // ==========================================
      const relationship = contactProfile?.relationship || "desconocido";
      await presenceManager.simulateHumanPresence(chat, realId, contactName, relationship, replyText);

      // 11. Enviar respuesta (Pasando por la aduana de stickers)
      await this._sendReplyWithStickers(chat.id._serialized, replyText, this.client);
      
      // --- LOG AMIGABLE: RESPUESTA LORENZO / Camila ---
      const timeOut = new Date().toLocaleTimeString('es-MX', { hour: '2-digit', minute: '2-digit', hour12: true });
      const agentName = personalityEngine.activeAgent === 'lorenzo' ? 'Lorenzo' : 'Camila';
      console.log(`\x1b[36m[%s]\x1b[0m \x1b[32m🤖 [${agentName}]:\x1b[0m %s`, timeOut, replyText);

      // 12. Almacenar AMBOS mensajes
      conversationContext.addMessage(realId, "user", messageText);
      conversationContext.addMessage(realId, "assistant", replyText);
      
      setImmediate(() => {
        memoryIngestionManager.handleConversationUpdate(realId, messageText, replyText)
          .catch(e => logger.error({ err: e, realId }, 'Error in memory ingestion sync'));
      });

    } catch (error) {
      logger.error({ err: error, messageId: message.id?._serialized }, 'Error processing incoming message');
    }
  }
}

module.exports = new MessageProcessor();